def main() -> None:
    doc = pymupdf.open(find_pdf())
    pics: dict[str, tuple[bytes, tuple[int, int]]] = {}
    for name in CROPS:
        im = crop_page(doc, name)
        if name not in PHOTOS:
            im = trim_margin(im)
        pics[name] = (image_stream(name, im).getvalue(), im.size)

    prs = Presentation()
    prs.slide_width = SLIDE_W
    prs.slide_height = SLIDE_H
    blank = prs.slide_layouts[6]
    total = len(SLIDES)
    for index, spec in enumerate(SLIDES, start=1):
        slide = prs.slides.add_slide(blank)
        pic = None
        if spec.image:
            data, size = pics[spec.image]
            pic = (io.BytesIO(data), size)
        if spec.kind == "title":
            add_title(slide, spec, pic)
        elif spec.kind == "section":
            add_section(slide, spec, pic, index, total)
        elif spec.kind == "numbers":
            add_numbers(slide, spec, index, total)
        elif spec.kind == "flags":
            add_flags(slide, spec, index, total)
        elif spec.kind == "close":
            add_close(slide, spec, index, total)
        else:
            add_figure(slide, spec, pic, index, total)
        slide.notes_slide.notes_text_frame.text = spec.notes
    prs.save(OUT)
    print(f"{total} slides -> {OUT}")


if __name__ == "__main__":
    main()
