def add_figure(slide, spec: Slide, pic, index, total):
    background(slide)
    header(slide, spec.title)
    stream, size = pic
    aspect = size[0] / size[1]
    top, bottom = Inches(1.35), SLIDE_H - Inches(0.62)
    pad = Inches(0.14)
    if aspect >= 1.9:
        img_h = Inches(3.7)
        card(slide, Inches(0.5), top, SLIDE_W - Inches(1.0), img_h)
        picture_fit(slide, stream, size, Inches(0.5) + pad, top + pad, SLIDE_W - Inches(1.0) - pad * 2, img_h - pad * 2)
        by = top + img_h + Inches(0.25)
        half = (len(spec.bullets) + 1) // 2
        col_w = (SLIDE_W - Inches(1.4)) // 2
        bullets(slide, Inches(0.5), by, col_w, Inches(1.5), spec.bullets[:half], size=16, gap=8)
        bullets(slide, Inches(0.5) + col_w + Inches(0.4), by, col_w, Inches(1.5), spec.bullets[half:], size=16, gap=8)
        if spec.warning:
            warning_bar(slide, Inches(0.5), bottom - Inches(0.62), SLIDE_W - Inches(1.0), spec.warning)
    else:
        img_w = Inches(7.7)
        card(slide, Inches(0.5), top, img_w, bottom - top)
        picture_fit(slide, stream, size, Inches(0.5) + pad, top + pad, img_w - pad * 2, bottom - top - pad * 2)
        tx = Inches(0.5) + img_w + Inches(0.4)
        tw = SLIDE_W - tx - Inches(0.5)
        bh = bottom - top - (Inches(0.85) if spec.warning else 0)
