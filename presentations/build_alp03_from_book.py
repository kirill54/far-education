def find_pdf() -> Path:
    candidates = []
    if len(sys.argv) > 1:
        candidates.append(Path(sys.argv[1]))
    if os.environ.get("ALP03_PDF"):
        candidates.append(Path(os.environ["ALP03_PDF"]))
    candidates.extend(
        [
            Path("/home/ubuntu/.cursor/projects/agent-repos-far-education/uploads/ALP_Module_03__1__35db.pdf"),
            ROOT / "ALP_Module_03.pdf",
        ]
    )
    for path in candidates:
        if path.is_file():
            return path
    raise SystemExit("Не найден PDF модуля 3. Передайте путь аргументом или ALP03_PDF.")


def crop_page(doc: pymupdf.Document, name: str) -> Image.Image:
    book, (x0, y0, x1, y1) = CROPS[name]
    page = doc[book - 94]
    pix = page.get_pixmap(dpi=DPI, clip=pymupdf.Rect(x0, y0, x1, y1), alpha=False)
    return Image.frombytes("RGB", (pix.width, pix.height), pix.samples)


def trim_margin(im: Image.Image, thresh: int = 247, pad: int = 10) -> Image.Image:
    """Срезает внешние почти белые поля. Внутренние просветы не трогает."""
    w, h = im.size
    px = im.load()

    def blank(xs, ys) -> bool:
        return all(min(px[x, y]) >= thresh for x in xs for y in ys)

    top = 0
    while top < h * 0.22 and blank(range(0, w, 4), [top]):
        top += 1
    bot = h - 1
    while bot > h * 0.78 and blank(range(0, w, 4), [bot]):
        bot -= 1
    left = 0
    while left < w * 0.18 and blank([left], range(0, h, 4)):
        left += 1
    right = w - 1
    while right > w * 0.82 and blank([right], range(0, h, 4)):
        right -= 1
    box = (max(0, left - pad), max(0, top - pad), min(w, right + pad + 1), min(h, bot + pad + 1))
    if box[2] - box[0] < 40 or box[3] - box[1] < 40:
        return im
    return im.crop(box)


def image_stream(name: str, im: Image.Image) -> io.BytesIO:
    buf = io.BytesIO()
    if name in PHOTOS:
        im.save(buf, "JPEG", quality=88, optimize=True)
    else:
        im.save(buf, "PNG", optimize=True)
    buf.seek(0)
    return buf


def rect(slide, x, y, w, h, fill, line=None, shape=MSO_SHAPE.RECTANGLE):
    shp = slide.shapes.add_shape(shape, x, y, w, h)
    shp.fill.solid()
    shp.fill.fore_color.rgb = fill
    if line is None:
        shp.line.fill.background()
    else:
        shp.line.color.rgb = line
        shp.line.width = Pt(0.75)
    shp.shadow.inherit = False
    if shape == MSO_SHAPE.ROUNDED_RECTANGLE:
        shp.adjustments[0] = 0.04
    return shp


def text(slide, x, y, w, h, s, size, bold=False, color=INK, align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP):
    box = slide.shapes.add_textbox(x, y, w, h)
    tf = box.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = 0
    tf.margin_top = tf.margin_bottom = 0
    tf.vertical_anchor = anchor
    lines = s.split("\n")
    for i, line in enumerate(lines):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        r = p.add_run()
        r.text = line
        f = r.font
        f.name = FONT
        f.size = Pt(size)
        f.bold = bold
        f.color.rgb = color
    return box


def set_bullet(p, color: RGBColor, indent_in: float = 0.3) -> None:
    pPr = p._p.get_or_add_pPr()
    pPr.set("marL", str(int(Inches(indent_in))))
    pPr.set("indent", str(-int(Inches(indent_in))))
    bu_clr = etree.SubElement(pPr, qn("a:buClr"))
    clr = etree.SubElement(bu_clr, qn("a:srgbClr"))
    clr.set("val", str(color))
    bu_font = etree.SubElement(pPr, qn("a:buFont"))
    bu_font.set("typeface", FONT)
    bu_char = etree.SubElement(pPr, qn("a:buChar"))
    bu_char.set("char", "•")


def bullets(slide, x, y, w, h, items, size=17, color=INK, bullet_color=BLUE, gap=10):
    box = slide.shapes.add_textbox(x, y, w, h)
    tf = box.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = 0
    tf.margin_top = tf.margin_bottom = 0
    for i, item in enumerate(items):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.space_after = Pt(gap)
        p.line_spacing = 1.08
        r = p.add_run()
        r.text = item
        r.font.name = FONT
        r.font.size = Pt(size)
        r.font.color.rgb = color
        set_bullet(p, bullet_color)
    return box


def picture_fit(slide, stream, px_size, x, y, w, h):
    iw, ih = px_size
    scale = min(w / iw, h / ih)
    pw, ph = int(iw * scale), int(ih * scale)
    px, py = x + (w - pw) // 2, y + (h - ph) // 2
    return slide.shapes.add_picture(stream, px, py, pw, ph)


def picture_cover(slide, stream, px_size, x, y, w, h, ax=0.5, ay=0.5):
    iw, ih = px_size
    pic = slide.shapes.add_picture(stream, x, y, w, h)
    target = w / h
    src = iw / ih
    if src > target:
        keep = target / src
        cut = 1 - keep
        pic.crop_left = cut * ax
        pic.crop_right = cut * (1 - ax)
    else:
        keep = src / target
        cut = 1 - keep
        pic.crop_top = cut * ay
        pic.crop_bottom = cut * (1 - ay)
    return pic


