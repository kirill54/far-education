# ── Сборка и проверка ──────────────────────────────────────────────────────

def norm(s: str) -> str:
    return s.lower().replace("ё", "е")


def stems(term: dict) -> list[str]:
    if term.get("k"):
        return [norm(k) for k in term["k"]]
    words = re.findall(r"[а-яёa-z]{4,}", norm(term["t"]))
    return [words[0][: max(4, len(words[0]) - 2)]] if words else [norm(term["t"])]


def lesson_text(lesson: Lesson) -> str:
    parts = []
    for s in lesson.slides:
        parts += [s.title, s.caption, s.warning, s.narration, *s.items]
        for key in ("subtitle", "callout"):
            parts.append(str(s.extra.get(key, "")))
        for key in ("topics", "flags"):
            parts += s.extra.get(key, [])
        for pair in s.extra.get("terms", []) + s.extra.get("cards", []) + s.extra.get("events", []):
            parts += pair
        for _, _, items in s.extra.get("columns", []):
            parts += items
    return norm(" ".join(parts))


def check() -> int:
    data = json.loads(TERMS.read_text())
    by_code = {lesson.code: lesson for lesson in LESSONS}
    missing, pending, unassigned = [], 0, []
    for number, module in data["modules"].items():
        for term in module["terms"]:
            code = term.get("l", "")
            if not code:
                unassigned.append(f"{number}: {term['t']}")
                continue
            lesson = by_code.get(code)
            if lesson is None:
                pending += 1
                continue
            body = lesson_text(lesson)
            if not any(re.search(r"(?<![а-яa-z])" + re.escape(k), body) for k in stems(term)):
                missing.append(f"{code}: {term['t']}")
    total = sum(len(m["terms"]) for m in data["modules"].values())
    print(f"Терминов {total}; в собранных уроках не найдено {len(missing)}; "
          f"ждут своих уроков {pending}; без урока {len(unassigned)}.")
    for line in missing + [f"без урока — {u}" for u in unassigned]:
        print("  ", line)
    return 1 if missing or unassigned else 0


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("codes", nargs="*", help="номера уроков, например 2.1 10.3")
    parser.add_argument("--check", action="store_true", help="только проверить покрытие терминов")
    args = parser.parse_args()
    if args.check:
        sys.exit(check())
    OUT.mkdir(exist_ok=True)
    for lesson in LESSONS:
        if not args.codes or lesson.code in args.codes:
            build(lesson.deck())
    sys.exit(check())


if __name__ == "__main__":
    main()
