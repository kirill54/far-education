def merged_pdf() -> Path:
    """Склеивает части так, что индекс 0 — книжная страница 268."""
    dest = Path(tempfile.gettempdir()) / "alp06_book.pdf"
    missing = [path for path in PARTS if not path.is_file()]
    if missing:
        raise SystemExit("Нет частей модуля 6:\n" + "\n".join(str(path) for path in missing))
    first, second, third = (pymupdf.open(path) for path in PARTS)
    doc = pymupdf.open()
    doc.insert_pdf(first, from_page=10, to_page=19)
    doc.insert_pdf(second)
    doc.insert_pdf(third)
    if doc.page_count != 56:
        raise SystemExit(f"Ожидалось 56 страниц книги, собрано {doc.page_count}.")
    doc.save(dest)
    return dest


