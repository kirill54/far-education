def merged_pdf() -> Path:
    """Склеивает части в PDF, где индекс 0 — книжная страница 176."""
    dest = Path(tempfile.gettempdir()) / "alp05_book.pdf"
    missing = [path for path in (*PARTS, MID_ZIP, *PARTS_TAIL) if not path.is_file()]
    if missing:
        raise SystemExit("Нет частей модуля 5:\n" + "\n".join(str(path) for path in missing))
    doc = pymupdf.open()
    for path in PARTS:
        doc.insert_pdf(pymupdf.open(path))
    with zipfile.ZipFile(MID_ZIP) as archive:
        names = sorted(
            (name for name in archive.namelist() if name.lower().endswith(".pdf")),
            key=lambda name: int(Path(name).stem.split("-")[-1]),
        )
        for name in names:
            doc.insert_pdf(pymupdf.open(stream=archive.read(name)))
    for path in PARTS_TAIL:
        doc.insert_pdf(pymupdf.open(path))
    if doc.page_count != 92:
        raise SystemExit(f"Ожидалось 92 страницы книги, собрано {doc.page_count}.")
    doc.save(dest)
    return dest


